-- 1. Batches.
insert into public.batches (year, is_visible)
select distinct batch_year, true from term_list
on conflict (year) do update set is_visible = true;

-- 2. Subjects: add missing codes; fill an empty title and missing credits, never overwrite.
insert into public.subjects (code, title, credits)
select distinct on (code) code, title, credits from term_list order by code, length(title) desc
on conflict (code) do update
  set title   = case when public.subjects.title = '' then excluded.title else public.subjects.title end,
      credits = coalesce(public.subjects.credits, excluded.credits);

-- 3. Programme curriculum (only programmes that exist in your programmes table).
insert into public.programme_subjects (programme_slug, subject_code)
select distinct p.slug, t.code
from term_list t
join public.programmes p on p.code = t.programme
on conflict do nothing;

-- 4. Codes for courses that have none, by exact title (ignoring case, spaces, punctuation and a
--    trailing "s"). Only a single, certain match is used.
with titles as (
  select distinct code, regexp_replace(lower(title), '[^a-z0-9]', '', 'g') as k from term_list
),
matches as (
  select c.id, min(t.code) as code, count(distinct t.code) as n
  from public.courses c
  join titles t
    on rtrim(regexp_replace(lower(c.title), '[^a-z0-9]', '', 'g'), 's') = rtrim(t.k, 's')
  where c.subject_code is null
  group by c.id
)
update public.courses c
   set subject_code = m.code
  from matches m
 where m.id = c.id and m.n = 1;

-- 5. File coded courses under the newest batch that takes them this term.
create temp table filing as
with newest as (
  select t.code, max(t.batch_year) as batch_year from term_list t
  join public.programmes p on p.code = t.programme
  group by t.code
)
select c.id as course_id,
       n.batch_year,
       least(10, greatest(1, (2026 - n.batch_year + 1) * 2)) as semester,
       array_agg(p.slug order by p.sort, p.slug) as slugs
from public.courses c
join newest n on n.code = c.subject_code
join term_list t on t.code = n.code and t.batch_year = n.batch_year
join public.programmes p on p.code = t.programme
where c.offered_to is null
group by c.id, n.batch_year;

update public.courses c
   set batch_year = f.batch_year,
       semester = f.semester,
       primary_programme_slug = f.slugs[1]
  from filing f
 where f.course_id = c.id;

delete from public.course_programmes cp
 using filing f
 where cp.course_id = f.course_id
   and cp.programme_slug <> all (f.slugs);

insert into public.course_programmes (course_id, programme_slug)
select f.course_id, unnest(f.slugs) from filing f
on conflict do nothing;

drop table term_list;
drop table filing;


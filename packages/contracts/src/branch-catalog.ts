const WINTER_COURSE_CODES = new Set<string>(Object.values(WINTER_2026_27_PROGRAMME_COURSES).flat());

const winterCoursesFor = (programmeCode: string) =>
  WINTER_2026_27_PROGRAMME_COURSES[programmeCode as keyof typeof WINTER_2026_27_PROGRAMME_COURSES] ?? [];

/**
 * Use the supplied Winter 2026-27 FFCS list as the exact map for every course
 * it names. Retain legacy placements only for older courses absent from that
 * document; never infer that a course is shared across every programme.
 */
export const BRANCH_CATALOG = [
  ...BASE_BRANCH_CATALOG.map((branch) => ({
    ...branch,
    courses: [
      ...new Set([
        ...branch.courses.filter((code) => !WINTER_COURSE_CODES.has(code)),
        ...winterCoursesFor(branch.id),
      ]),
    ],
  })),
  ...WINTER_2026_27_PROGRAMMES.map(([slug, id, name, shortName, tagline, description]) => ({
    slug,
    id,
    name,
    shortName,
    tagline,
    description,
    courses: [...winterCoursesFor(id)],
  })),
] as const;

export function extractCourseCode(value: string): string | null {
  return value.match(/\b([A-Z]{3}\d{4})\b/i)?.[1]?.toUpperCase() ?? null;
}

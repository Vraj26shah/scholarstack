export function extractCourseCode(value: string): string | null {
  return value.match(/\b([A-Z]{3}\d{4})\b/i)?.[1]?.toUpperCase() ?? null;
}

export function suggestedBranches(courseCode: string | null): string[] {
  if (!courseCode) return [];
  return BRANCH_CATALOG.filter((branch) => (branch.courses as readonly string[]).includes(courseCode)).map(
    (branch) => branch.slug,
  );
}

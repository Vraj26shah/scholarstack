#!/usr/bin/env node
// Splits the root .env into the files each app reads:
//   apps/web/.env.local  ← VITE_* only (public, baked into the site)
//   apps/api/.dev.vars   ← Worker keys (server-only, read by `wrangler dev`)
// Also flags empty or placeholder values so you know what's still missing.
import { writeFileSync } from 'node:fs';
import { PLACEHOLDER, WORKER_KEYS, readEnv } from './env-lib.mjs';

const env = readEnv();
const line = (k, v) => `${k}=${/[\s#"']/.test(v) ? JSON.stringify(v) : v}`;
const header = '# Generated by `pnpm env:sync` from the root .env. Edit .env, not this file.\n';

const web = [...env].filter(([k]) => k.startsWith('VITE_'));
const api = [...env].filter(([k]) => WORKER_KEYS.includes(k));
const render = (rows) => `${header}${rows.map(([k, v]) => line(k, v)).join('\n')}\n`;
writeFileSync('apps/web/.env.local', render(web));
writeFileSync('apps/api/.dev.vars', render(api));

const optional = new Set([
  'SUPABASE_LEGACY_JWT_SECRET',
  'CURRENT_INTAKE_YEAR',
  'BREVO_API_KEY',
  'CONVERTER_CALLBACK_URL',
]);
const todo = [...env].filter(
  ([k, v]) =>
    (WORKER_KEYS.includes(k) || k.startsWith('VITE_')) && !optional.has(k) && (!v || PLACEHOLDER.test(v)),
);
console.log(`✓ apps/web/.env.local  (${web.length} public values)`);
console.log(`✓ apps/api/.dev.vars   (${api.length} server values)`);
if (todo.length) {
  console.log(`\n${todo.length} still empty or placeholder:`);
  for (const [k] of todo) console.log(`  · ${k}`);
} else console.log('\nEverything is filled in.');
